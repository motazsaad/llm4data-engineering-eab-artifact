#!/usr/bin/env python3
"""Generate the size-scaling table and pgfplots figure.

Reads the qwen3-family scaling matrices (produced by run_scaling.sh into
out_scaling/) and emits LaTeX into the paper's table directory so the manuscript
can \\input them alongside the other generated tables.

The x axis is parameter count in billions; y is pass@1 pooled over both datasets
and both platforms. Transport retries are instrumented and were zero for every
run in this ladder, so the as-configured and first-attempt views coincide.

Usage:
    python3 scaling_tables.py --matrix-dir out_scaling --out out/paper
"""

import argparse
import os

import paper_tables as pt

FAMILY = ["qwen3:0.6b", "qwen3:1.7b", "qwen3:4b",
          "qwen3:8b", "qwen3:14b", "qwen3:32b"]
TASKS = ["T1", "T2", "T3"]


def params_b(model):
    """'qwen3:1.7b' -> 1.7"""
    return float(model.split(":", 1)[1].rstrip("bB"))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--matrix-dir", default="out_scaling")
    ap.add_argument("--out", default="out/paper")
    args = ap.parse_args()

    rows = pt.latest_per_cell(pt.load_rows(args.matrix_dir))
    cells = pt.aggregate(args.matrix_dir, rows)

    # Per family member: [passes, scored] per task.
    agg = {m: {t: [0, 0] for t in TASKS} for m in FAMILY}
    for (ds, task, plat, model), c in cells.items():
        if model in agg and task in agg[model]:
            agg[model][task][0] += c["passes"]
            agg[model][task][1] += c["scored"]

    os.makedirs(args.out, exist_ok=True)

    # ---- table ----
    lines = [
        "% Auto-generated by scaling_tables.py -- do not edit by hand.",
        r"\begin{tabular}{@{}lrrrrr@{}}",
        r"\toprule",
        r"\textbf{Size} & \textbf{T1 ingest} & \textbf{T2 ETL} "
        r"& \textbf{T3 join} & \textbf{Overall} & \textbf{n} \\",
        r"\midrule",
    ]
    for m in FAMILY:
        cell_txt, tot = [], [0, 0]
        for t in TASKS:
            p, s = agg[m][t]
            cell_txt.append(pt.fmt_rate(p, s))
            tot[0] += p
            tot[1] += s
        lines.append(f"{m.split(':')[1].upper()} & " + " & ".join(cell_txt) +
                     f" & {pt.fmt_rate(*tot)} & {tot[1]} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    with open(os.path.join(args.out, "paper_scaling_table.tex"), "w",
              encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    # ---- pgfplots figure ----
    def coords(task):
        pts = []
        for m in FAMILY:
            p, s = agg[m][task]
            y = (p / s) if s else 0.0
            pts.append(f"({params_b(m)},{y:.3f})")
        return " ".join(pts)

    overall = []
    for m in FAMILY:
        p = sum(agg[m][t][0] for t in TASKS)
        s = sum(agg[m][t][1] for t in TASKS)
        overall.append(f"({params_b(m)},{(p / s) if s else 0.0:.3f})")

    plot = [
        "% Auto-generated by scaling_tables.py -- do not edit by hand.",
        r"\begin{tikzpicture}",
        r"\begin{axis}[",
        r"  width=0.92\linewidth, height=5.4cm,",
        r"  xmode=log, log basis x=10,",
        r"  xlabel={model size (billion parameters)}, ylabel={pass@1},",
        r"  xmin=0.4, xmax=45, ymin=0, ymax=1,",
        r"  xtick={0.6,1.7,4,8,14,32},",
        r"  xticklabels={0.6,1.7,4,8,14,32},",
        r"  ytick={0,0.25,0.5,0.75,1.0},",
        r"  legend style={font=\footnotesize, at={(0.02,0.98)}, anchor=north west},",
        r"  grid=major, tick align=outside,",
        r"]",
        rf"\addplot[thick,mark=*,mark size=1.6pt] coordinates {{{coords('T1')}}};"
        r" \addlegendentry{T1 ingest}",
        rf"\addplot[thick,mark=square*,mark size=1.6pt] coordinates {{{coords('T2')}}};"
        r" \addlegendentry{T2 ETL}",
        rf"\addplot[thick,mark=triangle*,mark size=1.8pt] coordinates {{{coords('T3')}}};"
        r" \addlegendentry{T3 join}",
        rf"\addplot[thick,dashed,mark=diamond*,mark size=1.6pt] coordinates {{{' '.join(overall)}}};"
        r" \addlegendentry{overall}",
        r"\end{axis}",
        r"\end{tikzpicture}",
    ]
    with open(os.path.join(args.out, "paper_scaling_plot.tex"), "w",
              encoding="utf-8") as fh:
        fh.write("\n".join(plot) + "\n")

    print("scaling rows:")
    for m in FAMILY:
        tot = [sum(agg[m][t][0] for t in TASKS),
               sum(agg[m][t][1] for t in TASKS)]
        print(f"  {m:14s} T1={pt.fmt_rate(*agg[m]['T1'])} "
              f"T2={pt.fmt_rate(*agg[m]['T2'])} T3={pt.fmt_rate(*agg[m]['T3'])} "
              f"overall={pt.fmt_rate(*tot)} n={tot[1]}")
    print(f"written to {args.out}/")


if __name__ == "__main__":
    main()
